export const translations: Record<Language, Record<MessageKey, string>> = { it, en }

export function translate(
  language: Language,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = translations[language][key] ?? translations.it[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  )
}

export function getDateLocale(language: Language): Locale {
  return language === 'en' ? enUS : itLocale
}
